import assert from "node:assert/strict";
import { JSDOM } from "jsdom";
const dom = new JSDOM("", { url: "http://localhost/" });
Object.assign(globalThis, { window: dom.window, localStorage: dom.window.localStorage });
const { loadWorkspacePanelOpen } = await import("../store/layout");
assert.equal(loadWorkspacePanelOpen("fresh"), false, "an unsaved project starts with a collapsed dock");
assert.equal(loadWorkspacePanelOpen(""), false, "the unbound welcome also starts collapsed");
localStorage.setItem("deepzora.workspacePanel.open", "1");
assert.equal(loadWorkspacePanelOpen(""), true, "an explicit welcome preference restores independently");
assert.equal(loadWorkspacePanelOpen("fresh"), false, "the welcome preference does not override another project");
localStorage.setItem("deepzora.workspacePanel.open.project-a", "0");
assert.equal(loadWorkspacePanelOpen("project-a"), false);
localStorage.setItem("deepzora.workspacePanel.open.project-a", "1");
assert.equal(loadWorkspacePanelOpen("project-a"), true);
assert.equal(loadWorkspacePanelOpen("project-b"), false, "another unsaved project keeps its own default");
dom.window.close();
console.log("current project dock preference persists independently");
