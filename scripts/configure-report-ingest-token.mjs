#!/usr/bin/env node
// Produce SQL containing only the digest of a report-only token. Never print
// the original token or include it in the generated SQL/migration history.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

const [envFile = "supabase/report-client.env.local", output = "supabase/.temp/report-token.sql"] = process.argv.slice(2);
const content = readFileSync(envFile, "utf8");
const line = content.split(/\r?\n/).find((line) => line.startsWith("DEEPZORA_REPORT_TOKEN="));
const token = line?.slice("DEEPZORA_REPORT_TOKEN=".length).trim();
if (!token || !/^[0-9a-f]{64}$/.test(token)) {
  throw new Error("Use a report-only token generated by openssl rand -hex 32.");
}
const digest = createHash("sha256").update(token).digest("hex");
const sql = `insert into public.deepzora_report_ingest_settings (id, token_sha256)
values (1, '${digest}')
on conflict (id) do update set token_sha256 = excluded.token_sha256, updated_at = now();\n`;
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, sql, { mode: 0o600 });
console.log(`Report token digest SQL written to ${output}; original token not logged.`);
